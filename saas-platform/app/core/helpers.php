<?php
declare(strict_types=1);

final class Config
{
    private static ?array $cfg = null;

    public static function path(): string { return DATA_DIR . '/config.php'; }

    public static function all(): array
    {
        if (self::$cfg === null) {
            self::$cfg = is_file(self::path()) ? (array) require self::path() : [];
        }
        return self::$cfg;
    }

    public static function get(string $k, mixed $d = null): mixed { return self::all()[$k] ?? $d; }

    public static function installed(): bool { return is_file(self::path()) && !empty(self::all()['app_key']); }

    public static function write(array $cfg): void
    {
        $php = "<?php\n// Generated by setup. Keep private.\nreturn " . var_export($cfg, true) . ";\n";
        file_put_contents(self::path(), $php, LOCK_EX);
        @chmod(self::path(), 0640);
        self::$cfg = $cfg;
        if (function_exists('opcache_invalidate')) { @opcache_invalidate(self::path(), true); }
    }

    public static function reset(): void { self::$cfg = null; }
}

/* ---------- output ---------- */
function e(mixed $v): string { return htmlspecialchars((string) ($v ?? ''), ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8'); }
function ej(mixed $v): string { return json_encode($v, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_HEX_TAG | JSON_HEX_AMP | JSON_HEX_APOS | JSON_HEX_QUOT); }
function jd(?string $s, mixed $default = []): mixed
{
    if ($s === null || $s === '') return $default;
    $v = json_decode($s, true);
    return $v === null ? $default : $v;
}
function je(mixed $v): string { return json_encode($v, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES); }

/* ---------- request ---------- */
function req_method(): string { return strtoupper($_SERVER['REQUEST_METHOD'] ?? 'GET'); }
function is_post(): bool { return req_method() === 'POST'; }
function req_path(): string
{
    $p = rawurldecode((string) parse_url($_SERVER['REQUEST_URI'] ?? '/', PHP_URL_PATH));
    $p = '/' . ltrim(preg_replace('#/+#', '/', $p), '/');
    return $p;
}
function req_host(): string
{
    $h = strtolower((string) ($_SERVER['HTTP_HOST'] ?? $_SERVER['SERVER_NAME'] ?? 'localhost'));
    $h = preg_replace('/[^a-z0-9.\-:\[\]]/', '', $h);
    return $h;
}
function host_without_port(string $h): string { return preg_replace('/:\d+$/', '', $h); }
function is_https(): bool
{
    return (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off')
        || (($_SERVER['HTTP_X_FORWARDED_PROTO'] ?? '') === 'https')
        || (($_SERVER['SERVER_PORT'] ?? '') === '443');
}
function base_url(): string { return (is_https() ? 'https' : 'http') . '://' . req_host(); }
function abs_url(string $path): string { return str_starts_with($path, 'http') ? $path : base_url() . '/' . ltrim($path, '/'); }
function client_ip(): string { return substr((string) ($_SERVER['REMOTE_ADDR'] ?? '0.0.0.0'), 0, 45); }
function input(string $k, mixed $d = null): mixed { return $_POST[$k] ?? $_GET[$k] ?? $d; }
function in_str(string $k, string $d = '', int $max = 5000): string
{
    $v = $_POST[$k] ?? $_GET[$k] ?? $d;
    if (is_array($v)) return $d;
    $v = trim(str_replace("\0", '', (string) $v));
    return mb_substr($v, 0, $max);
}
function in_int(string $k, int $d = 0): int { $v = $_POST[$k] ?? $_GET[$k] ?? null; return is_numeric($v) ? (int) $v : $d; }
function in_float(string $k, ?float $d = null): ?float
{
    $v = $_POST[$k] ?? $_GET[$k] ?? null;
    if ($v === null || $v === '') return $d;
    $v = str_replace([' ', '€'], '', (string) $v);
    if (preg_match('/^\d{1,3}(\.\d{3})+(,\d+)?$/', $v)) { $v = str_replace('.', '', $v); }
    $v = str_replace(',', '.', $v);
    return is_numeric($v) ? round((float) $v, 2) : $d;
}
function in_bool(string $k): bool { return !empty($_POST[$k]) && $_POST[$k] !== '0'; }
function in_arr(string $k): array { $v = $_POST[$k] ?? $_GET[$k] ?? []; return is_array($v) ? $v : []; }
function wants_json(): bool
{
    return str_contains($_SERVER['HTTP_ACCEPT'] ?? '', 'application/json')
        || ($_SERVER['HTTP_X_REQUESTED_WITH'] ?? '') === 'XMLHttpRequest';
}

/* ---------- responses ---------- */
function redirect(string $to, int $code = 302): never
{
    if (!headers_sent()) { header('Location: ' . $to, true, $code); }
    exit;
}
function back(string $fallback = '/'): never
{
    $ref = $_SERVER['HTTP_REFERER'] ?? '';
    $ok = $ref && parse_url($ref, PHP_URL_HOST) === host_without_port(req_host());
    redirect($ok ? $ref : $fallback);
}
function json_out(mixed $data, int $code = 200): never
{
    http_response_code($code);
    header('Content-Type: application/json; charset=utf-8');
    header('Cache-Control: no-store');
    echo je($data);
    exit;
}
function noindex(): void { header('X-Robots-Tag: noindex, nofollow', true); }
function security_headers(bool $admin = false): void
{
    header('X-Content-Type-Options: nosniff');
    header('Referrer-Policy: strict-origin-when-cross-origin');
    header('X-Frame-Options: SAMEORIGIN');
    header('Permissions-Policy: camera=(), microphone=(), geolocation=()');
    if ($admin) {
        header('Cache-Control: no-store, private');
        noindex();
    }
}

/* ---------- sessions & flash ---------- */
function session_start_scoped(string $name): void
{
    if (session_status() === PHP_SESSION_ACTIVE) return;
    session_name($name);
    session_set_cookie_params(['lifetime' => 0, 'path' => '/', 'secure' => is_https(), 'httponly' => true, 'samesite' => 'Lax']);
    ini_set('session.use_strict_mode', '1');
    ini_set('session.use_only_cookies', '1');
    ini_set('session.gc_maxlifetime', '7200');
    $dir = DATA_DIR . '/tmp/sessions';
    if (!is_dir($dir)) { @mkdir($dir, 0770, true); }
    if (is_writable($dir)) { session_save_path($dir); }
    session_start();
}
function flash(string $type, string $msg): void { $_SESSION['_flash'][] = ['type' => $type, 'msg' => $msg]; }
function flashes(): array { $f = $_SESSION['_flash'] ?? []; unset($_SESSION['_flash']); return $f; }
function old(string $k, mixed $d = ''): mixed { return $_SESSION['_old'][$k] ?? $d; }
function keep_old(): void { $_SESSION['_old'] = array_map(fn($v) => is_string($v) ? mb_substr($v, 0, 5000) : $v, $_POST); }
function clear_old(): void { unset($_SESSION['_old']); }

/* ---------- CSRF ---------- */
function csrf_token(): string
{
    if (empty($_SESSION['_csrf'])) { $_SESSION['_csrf'] = bin2hex(random_bytes(32)); }
    return $_SESSION['_csrf'];
}
function csrf_field(): string { return '<input type="hidden" name="_csrf" value="' . e(csrf_token()) . '">'; }
function csrf_valid(): bool
{
    $t = $_POST['_csrf'] ?? $_SERVER['HTTP_X_CSRF_TOKEN'] ?? '';
    return is_string($t) && !empty($_SESSION['_csrf']) && hash_equals($_SESSION['_csrf'], $t);
}
function csrf_check(): void
{
    if (!csrf_valid()) {
        if (wants_json()) json_out(['ok' => false, 'error' => 'Η φόρμα έληξε. Ανανεώστε τη σελίδα και δοκιμάστε ξανά.'], 419);
        http_response_code(419);
        echo View::render('system/error', ['code' => 419, 'title' => 'Η φόρμα έληξε', 'message' => 'Για λόγους ασφαλείας η φόρμα έληξε. Επιστρέψτε, ανανεώστε τη σελίδα και δοκιμάστε ξανά.']);
        exit;
    }
}

/* ---------- strings ---------- */
function slugify(string $s, int $max = 90): string
{
    static $map = null;
    if ($map === null) {
        $map = [
            'ου' => 'ou', 'ού' => 'ou', 'Ου' => 'ou', 'ΟΥ' => 'ou', 'αυ' => 'av', 'αύ' => 'av', 'ευ' => 'ev', 'εύ' => 'ev', 'μπ' => 'b', 'ντ' => 'nt', 'γκ' => 'gk', 'γγ' => 'ng', 'τσ' => 'ts', 'τζ' => 'tz', 'θ' => 'th', 'χ' => 'ch', 'ψ' => 'ps',
            'α' => 'a', 'ά' => 'a', 'β' => 'v', 'γ' => 'g', 'δ' => 'd', 'ε' => 'e', 'έ' => 'e', 'ζ' => 'z', 'η' => 'i', 'ή' => 'i', 'ι' => 'i', 'ί' => 'i', 'ϊ' => 'i', 'ΐ' => 'i',
            'κ' => 'k', 'λ' => 'l', 'μ' => 'm', 'ν' => 'n', 'ξ' => 'x', 'ο' => 'o', 'ό' => 'o', 'π' => 'p', 'ρ' => 'r', 'σ' => 's', 'ς' => 's', 'τ' => 't', 'υ' => 'y', 'ύ' => 'y', 'ϋ' => 'y', 'ΰ' => 'y',
            'φ' => 'f', 'ω' => 'o', 'ώ' => 'o',
        ];
    }
    $s = mb_strtolower($s, 'UTF-8');
    $s = strtr($s, $map);
    if (function_exists('transliterator_transliterate')) {
        $t = transliterator_transliterate('Any-Latin; Latin-ASCII', $s);
        if ($t !== false) $s = $t;
    } else {
        $s = iconv('UTF-8', 'ASCII//TRANSLIT//IGNORE', $s) ?: $s;
    }
    $s = strtolower(preg_replace('/[^a-zA-Z0-9]+/', '-', $s));
    $s = trim($s, '-');
    if (strlen($s) > $max) { $s = rtrim(substr($s, 0, $max), '-'); }
    return $s !== '' ? $s : 'item';
}
function str_fold(string $s): string
{
    $s = mb_strtolower($s, 'UTF-8');
    $s = strtr($s, ['ά' => 'α', 'έ' => 'ε', 'ή' => 'η', 'ί' => 'ι', 'ϊ' => 'ι', 'ΐ' => 'ι', 'ό' => 'ο', 'ύ' => 'υ', 'ϋ' => 'υ', 'ΰ' => 'υ', 'ώ' => 'ω', 'ς' => 'σ']);
    if (class_exists('Normalizer')) {
        $s = preg_replace('/\p{Mn}+/u', '', Normalizer::normalize($s, Normalizer::FORM_D) ?: $s);
    }
    return $s;
}
function excerpt(?string $html, int $len = 160): string
{
    $t = trim(preg_replace('/\s+/u', ' ', html_entity_decode(strip_tags((string) $html), ENT_QUOTES, 'UTF-8')));
    return mb_strlen($t) > $len ? rtrim(mb_substr($t, 0, $len - 1)) . '…' : $t;
}
function random_token(int $bytes = 24): string { return rtrim(strtr(base64_encode(random_bytes($bytes)), '+/', '-_'), '='); }

/* ---------- money / dates ---------- */
function money(?float $v, string $cur = '€'): string
{
    return number_format((float) $v, 2, ',', '.') . ' ' . $cur;
}
function now(): string { return date('Y-m-d H:i:s'); }
function today(): string { return date('Y-m-d'); }
function fmt_date(?string $d, bool $time = false): string
{
    if (!$d) return '—';
    $ts = strtotime($d);
    return $ts ? date($time ? 'd/m/Y H:i' : 'd/m/Y', $ts) : '—';
}
function days_until(?string $date): ?int
{
    if (!$date) return null;
    $a = new DateTimeImmutable(today());
    $b = new DateTimeImmutable(substr($date, 0, 10));
    return (int) $a->diff($b)->format('%r%a');
}
function add_months(string $date, int $months): string
{
    $d = new DateTimeImmutable(substr($date, 0, 10));
    $day = (int) $d->format('d');
    $t = $d->modify('first day of this month')->modify("+$months months");
    $last = (int) $t->format('t');
    return $t->setDate((int) $t->format('Y'), (int) $t->format('m'), min($day, $last))->format('Y-m-d');
}

/* ---------- pagination ---------- */
function paginate(int $total, int $perPage, int $page): array
{
    $pages = max(1, (int) ceil($total / max(1, $perPage)));
    $page = max(1, min($page, $pages));
    return ['total' => $total, 'per' => $perPage, 'page' => $page, 'pages' => $pages, 'offset' => ($page - 1) * $perPage,
        'from' => $total ? ($page - 1) * $perPage + 1 : 0, 'to' => min($total, $page * $perPage)];
}
function query_with(array $changes): string
{
    $q = array_merge($_GET, $changes);
    $q = array_filter($q, fn($v) => $v !== null && $v !== '');
    return $q ? '?' . http_build_query($q) : '?';
}

/* ---------- rate limiting (per DB) ---------- */
function rate_limit(PDO $db, string $key, int $max, int $windowSeconds): bool
{
    $now = time();
    $row = db_one($db, 'SELECT window_start, hits FROM rate_limits WHERE key = ?', [$key]);
    if (!$row || $row['window_start'] < $now - $windowSeconds) {
        db_exec($db, 'INSERT OR REPLACE INTO rate_limits(key, window_start, hits) VALUES(?,?,1)', [$key, $now]);
        return true;
    }
    if ($row['hits'] >= $max) return false;
    db_exec($db, 'UPDATE rate_limits SET hits = hits + 1 WHERE key = ?', [$key]);
    return true;
}

