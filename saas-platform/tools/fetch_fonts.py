"""Dev tool: download Google Fonts (OFL) as self-hosted woff2 (greek + latin subsets) per template.
Run once at build time; production never contacts Google. Usage: python3 tools/fetch_fonts.py"""
import json, os, re, urllib.request, urllib.parse
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36'
WEIGHTS = {
 'Noto Serif Display': 'ital,wght@0,300;0,400;0,500;1,300;1,400', 'Commissioner': 'wght@300;400;500;600',
 'Sofia Sans Condensed': 'wght@600;700;800;900', 'IBM Plex Sans': 'wght@400;500;600',
 'M PLUS Rounded 1c': 'wght@500;800', 'Manrope': 'wght@400;500;600;700',
 'GFS Didot': None, 'Noto Sans': 'wght@300;400;500;600',
 'Fira Sans': 'wght@300;400;500;600',
 'EB Garamond': 'ital,wght@0,400;0,500;1,400', 'Open Sans': 'wght@300;400;600',
 'Roboto Condensed': 'ital,wght@0,500;0,700;0,800;1,700;1,800', 'Roboto': 'wght@400;500;700',
 'Comfortaa': 'wght@500;700', 'Ubuntu': 'wght@400;500;700',
 'Sofia Sans Semi Condensed': 'wght@500;700;800', 'Sofia Sans': 'wght@400;500;600;700', 'Roboto Mono': 'wght@400;500',
 'Literata': 'ital,opsz,wght@0,7..72,400;0,7..72,600;1,7..72,400', 'Source Sans 3': 'wght@400;500;600;700',
}
def get(url, binary=False):
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(req, timeout=30) as r:
        data = r.read()
    return data if binary else data.decode('utf-8')
for key in sorted(os.listdir(os.path.join(ROOT, 'templates'))):
    man = os.path.join(ROOT, 'templates', key, 'theme.json')
    if not os.path.isfile(man): continue
    fonts = [f for f in json.load(open(man, encoding='utf-8')).get('fonts', {}).values() if f]
    fonts = list(dict.fromkeys(fonts))
    outdir = os.path.join(ROOT, 'templates', key, 'assets', 'fonts'); os.makedirs(outdir, exist_ok=True)
    css_out = ['/* Self-hosted fonts (SIL Open Font License) — generated by tools/fetch_fonts.py */']
    for fam in fonts:
        spec = WEIGHTS.get(fam)
        q = 'family=' + urllib.parse.quote_plus(fam) + ((':' + spec) if spec else '') + '&display=swap'
        css = get('https://fonts.googleapis.com/css2?' + q)
        for subset, block in re.findall(r'/\* ([a-z-]+) \*/\s*(@font-face\s*{[^}]+})', css):
            if subset not in ('greek', 'latin'): continue
            url = re.search(r'url\((https://[^)]+\.woff2)\)', block).group(1)
            w = re.search(r'font-weight:\s*([^;]+);', block).group(1).strip()
            st = re.search(r'font-style:\s*([^;]+);', block).group(1).strip()
            fn = re.sub(r'[^a-z0-9]+', '-', fam.lower()) + f'-{st}-{w.replace(" ", "_")}-{subset}.woff2'
            path = os.path.join(outdir, fn)
            if not os.path.exists(path):
                open(path, 'wb').write(get(url, True))
            css_out.append(block.replace(url, 'fonts/' + fn))
    open(os.path.join(ROOT, 'templates', key, 'assets', 'fonts.css'), 'w', encoding='utf-8').write('\n'.join(css_out) + '\n')
    print(key, len(os.listdir(outdir)), 'files')
